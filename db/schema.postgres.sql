-- PostgreSQL schema snapshot for the NUST Student Accounts academic demo.
-- Apply only to a fresh project. The live DBS project already has these tables.
-- All public tables are RLS-protected and intentionally have no client policies.
-- The Flask backend uses server-only database/service credentials.

create table public.faculties (
  id bigint generated by default as identity primary key,
  name text not null unique
);
create table public.programmes (
  id bigint generated by default as identity primary key,
  faculty_id bigint not null references public.faculties(id) on delete restrict,
  name text not null unique,
  award_level text not null default 'Undergraduate'
);
create table public.sponsors (
  id bigint generated by default as identity primary key,
  display_name text not null,
  sponsor_type text not null check (sponsor_type in ('Family','Self-funded','Scholarship'))
);
create table public.students (
  id bigint generated by default as identity primary key,
  student_no text not null unique,
  first_name text not null,
  last_name text not null,
  programme_id bigint not null references public.programmes(id) on delete restrict,
  status text not null default 'Registered' check (status in ('Registered','On attachment','Deferred'))
);
create table public.student_sponsors (
  student_id bigint not null references public.students(id) on delete cascade,
  sponsor_id bigint not null references public.sponsors(id) on delete cascade,
  relationship text not null,
  primary key (student_id, sponsor_id)
);
create table public.academic_semesters (
  id bigint generated by default as identity primary key,
  academic_year text not null,
  semester_number smallint not null check (semester_number in (1,2)),
  starts_on date not null,
  ends_on date not null,
  check (ends_on >= starts_on),
  unique (academic_year, semester_number)
);
create table public.fee_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text
);
create table public.semester_fees (
  id bigint generated by default as identity primary key,
  semester_id bigint not null references public.academic_semesters(id) on delete restrict,
  faculty_id bigint not null references public.faculties(id) on delete restrict,
  fee_type_id bigint not null references public.fee_types(id) on delete restrict,
  amount_cents bigint not null check (amount_cents >= 0),
  currency text not null check (currency in ('USD','ZWG')),
  unique (semester_id, faculty_id, fee_type_id)
);
create table public.invoices (
  id bigint generated by default as identity primary key,
  invoice_no text not null unique,
  student_id bigint not null references public.students(id) on delete restrict,
  semester_id bigint not null references public.academic_semesters(id) on delete restrict,
  issued_on date not null,
  due_on date not null,
  status text not null default 'Open' check (status in ('Open','Paid','Void')),
  check (due_on >= issued_on),
  unique (student_id, semester_id)
);
create table public.invoice_lines (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.invoices(id) on delete cascade,
  fee_type_id bigint not null references public.fee_types(id) on delete restrict,
  description text not null,
  amount_cents bigint not null check (amount_cents >= 0),
  currency text not null check (currency in ('USD','ZWG'))
);
create table public.payments (
  id bigint generated by default as identity primary key,
  receipt_no text not null unique,
  student_id bigint not null references public.students(id) on delete restrict,
  paid_on date not null,
  amount_cents bigint not null check (amount_cents > 0),
  currency text not null check (currency in ('USD','ZWG')),
  method text not null check (method in ('EcoCash','Bank transfer','RTGS')),
  reference text,
  recorded_by text not null default 'Student accounts demo'
);
create table public.payment_allocations (
  payment_id bigint not null references public.payments(id) on delete cascade,
  invoice_id bigint not null references public.invoices(id) on delete restrict,
  amount_cents bigint not null check (amount_cents > 0),
  primary key (payment_id, invoice_id)
);
create table public.employee_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null check (role in ('system_admin','finance_manager','finance','accountant','payments_clerk','student_records','auditor')),
  is_active boolean not null default true,
  invited_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table public.employee_web_sessions (
  id bigint generated by default as identity primary key,
  session_key_hash text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  access_token text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index programmes_faculty_id_idx on public.programmes(faculty_id);
create index students_programme_id_idx on public.students(programme_id);
create index students_status_idx on public.students(status);
create index student_sponsors_sponsor_id_idx on public.student_sponsors(sponsor_id);
create index semester_fees_faculty_id_idx on public.semester_fees(faculty_id);
create index semester_fees_fee_type_id_idx on public.semester_fees(fee_type_id);
create index invoices_student_id_idx on public.invoices(student_id);
create index invoices_semester_id_idx on public.invoices(semester_id);
create index invoices_status_idx on public.invoices(status);
create index invoice_lines_invoice_id_idx on public.invoice_lines(invoice_id);
create index invoice_lines_fee_type_id_idx on public.invoice_lines(fee_type_id);
create index payments_student_id_idx on public.payments(student_id);
create index payments_paid_on_idx on public.payments(paid_on);
create index payment_allocations_invoice_id_idx on public.payment_allocations(invoice_id);
create index employee_profiles_role_active_idx on public.employee_profiles(role, is_active);
create index employee_profiles_invited_by_idx on public.employee_profiles(invited_by);
create index audit_logs_created_at_idx on public.audit_logs(created_at desc);
create index audit_logs_actor_user_id_idx on public.audit_logs(actor_user_id);
create index employee_web_sessions_user_id_idx on public.employee_web_sessions(user_id);
create index employee_web_sessions_expires_at_idx on public.employee_web_sessions(expires_at);

